<?php
session_start();

/* ==========================================================================
	文字コード設定
========================================================================== */
mb_language('Japanese');
mb_internal_encoding('UTF-8');

/* ==========================================================================
	直接アクセス対策
========================================================================== */
if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
	header('Location: ./');
	exit;
}

/* ==========================================================================
	値の取得
========================================================================== */
$shubetsu = isset($_POST['shubetsu']) ? trim($_POST['shubetsu']) : '';
$name = isset($_POST['name']) ? trim($_POST['name']) : '';
$kana = isset($_POST['kana']) ? trim($_POST['kana']) : '';
$todoufuken = isset($_POST['todoufuken']) ? trim($_POST['todoufuken']) : '';
$shichouson = isset($_POST['shichouson']) ? trim($_POST['shichouson']) : '';
$mail = isset($_POST['mail']) ? trim($_POST['mail']) : '';
$tel = isset($_POST['tel']) ? trim($_POST['tel']) : '';
$message = isset($_POST['message']) ? trim($_POST['message']) : '';

/* ==========================================================================
	改行コード統一
========================================================================== */
$message = str_replace(array("\r\n", "\r"), "\n", $message);

/* ==========================================================================
	バリデーション
========================================================================== */
$errors = array();

if ($shubetsu === '') $errors[] = 'お問い合わせ種別を選択してください。';
if ($name === '') $errors[] = 'お名前を入力してください。';
if ($kana === '') $errors[] = 'ふりがなを入力してください。';
if ($todoufuken === '') $errors[] = '住所：都道府県を入力してください。';
if ($shichouson === '') $errors[] = '住所：市区町村を入力してください。';
if ($mail === '') $errors[] = 'メールアドレスを入力してください。';
if ($message === '') $errors[] = 'ご相談・お問い合わせ内容を入力してください。';

if ($mail !== '' && !filter_var($mail, FILTER_VALIDATE_EMAIL)) {
	$errors[] = 'メールアドレスの形式が正しくありません。';
}

if ($tel !== '' && !preg_match('/^\d{2,4}-?\d{2,4}-?\d{3,4}$/', $tel)) {
	$errors[] = 'お電話番号の形式が正しくありません。';
}

/* ==========================================================================
	エラー時は入力画面へ戻す
========================================================================== */
if (!empty($errors)) {
	$_SESSION['errors'] = $errors;
	$_SESSION['old'] = $_POST;
	header('Location: ./');
	exit;
}

/* ==========================================================================
	メール設定
========================================================================== */
$admin_mail = 'eto@mont.jp'; // 本番用に変更
$from_mail = 'eto@mont.jp';  // 本番用に変更
$site_name = 'お問い合わせフォーム';

/* ==========================================================================
	件名
========================================================================== */
$subject_admin = '【' . $site_name . '】お問い合わせを受け付けました';
$subject_user = '【' . $site_name . '】お問い合わせありがとうございます';

/* ==========================================================================
	管理者宛本文
========================================================================== */
$body_admin = <<<EOT
{$site_name} よりお問い合わせがありました。

【お問い合わせ種別】
{$shubetsu}

【お名前】
{$name}

【ふりがな】
{$kana}

【住所：都道府県】
{$todoufuken}

【住所：市区町村】
{$shichouson}

【メールアドレス】
{$mail}

【お電話番号】
{$tel}

【ご相談・お問い合わせ内容】
{$message}

EOT;

/* ==========================================================================
	自動返信本文
========================================================================== */
$body_user = <<<EOT
{$name} 様

このたびはお問い合わせいただきありがとうございます。
以下の内容で受け付けいたしました。

【お問い合わせ種別】
{$shubetsu}

【お名前】
{$name}

【ふりがな】
{$kana}

【住所：都道府県】
{$todoufuken}

【住所：市区町村】
{$shichouson}

【メールアドレス】
{$mail}

【お電話番号】
{$tel}

【ご相談・お問い合わせ内容】
{$message}

内容を確認のうえ、担当よりご連絡いたします。
しばらくお待ちください。

※このメールは自動送信です。

EOT;

/* ==========================================================================
	ヘッダー
========================================================================== */
$headers_admin = array(
	'From: ' . mb_encode_mimeheader($site_name) . ' <' . $from_mail . '>',
	'Reply-To: ' . $mail,
	'MIME-Version: 1.0',
	'Content-Type: text/plain; charset=UTF-8'
);

$headers_user = array(
	'From: ' . mb_encode_mimeheader($site_name) . ' <' . $from_mail . '>',
	'Reply-To: ' . $from_mail,
	'MIME-Version: 1.0',
	'Content-Type: text/plain; charset=UTF-8'
);

/* ==========================================================================
	メール送信
========================================================================== */
$is_admin_sent = mb_send_mail(
	$admin_mail,
	$subject_admin,
	$body_admin,
	implode("\r\n", $headers_admin)
);

$is_user_sent = mb_send_mail(
	$mail,
	$subject_user,
	$body_user,
	implode("\r\n", $headers_user)
);

/* ==========================================================================
	送信結果確認
========================================================================== */
if (!$is_admin_sent || !$is_user_sent) {
	echo '<pre>';
	echo '管理者宛: ' . ($is_admin_sent ? '成功' : '失敗') . "\n";
	echo '自動返信: ' . ($is_user_sent ? '成功' : '失敗') . "\n";
	echo '</pre>';
	exit;
}
/* ==========================================================================
	送信失敗時
========================================================================== */
if (!$is_admin_sent || !$is_user_sent) {
	$_SESSION['errors'] = array('メールの送信に失敗しました。時間をおいて再度お試しください。');
	$_SESSION['old'] = $_POST;
	header('Location: ./');
	exit;
}

/* ==========================================================================
	完了後セッション破棄
========================================================================== */
unset($_SESSION['errors']);
unset($_SESSION['old']);
unset($_SESSION['contact']);

/* ==========================================================================
	完了ページへ
========================================================================== */
header('Location: ./thanks.php');
exit;